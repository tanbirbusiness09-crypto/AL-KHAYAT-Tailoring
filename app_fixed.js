function closeModal() {
  const modal = document.getElementById('product-modal');
  modal.classList.remove('active');
  // Reset zoom state
  const modalImg = modal.querySelector('.modal-img');
  if (modalImg) modalImg.classList.remove('zoomed');
}

function changeQty(d) {
  const el = document.getElementById('modal-qty');
  let v = parseInt(el.textContent) + d;
  if (v < 1) v = 1;
  el.textContent = v;
}

// ============ CART ============
function addToCart(id) {
  const p = products.find(x => x.id === id);
  if (!p) return;
  const existing = cart.find(c => c.id === id);
  if (existing) existing.qty++;
  else cart.push({ ...p, qty: 1 });
  updateCartUI();
  openCart();
}

function removeFromCart(id) {
  cart = cart.filter(c => c.id !== id);
  updateCartUI();
}

function updateCartUI() {
  const badge = document.querySelector('.cart-badge');
  const total = cart.reduce((s, c) => s + c.qty, 0);
  badge.textContent = total;
  const items = document.getElementById('cart-items');
  const footer = document.getElementById('cart-footer');
  if (cart.length === 0) {
    items.innerHTML = `<div class="cart-empty"><div style="font-size:3rem;margin-bottom:16px">🛒</div><p>${t('cart_empty')}</p></div>`;
    footer.style.display = 'none';
  } else {
    const totalPrice = cart.reduce((s, c) => s + c.price * c.qty, 0);
    items.innerHTML = cart.map(c => {
      const name = currentLang === 'en' ? c.name_en : c.name_ar;
      return `<div class="cart-item">
        <img src="${c.img}" alt="${name}">
        <div class="cart-item-info">
          <h4>${name}</h4>
          <div class="price">SAR ${c.price} × ${c.qty}</div>
        </div>
        <button class="cart-item-remove" onclick="removeFromCart(${c.id})">✕</button>
      </div>`;
    }).join('');
    footer.style.display = 'block';
    footer.innerHTML = `
      <div class="cart-total"><span>${t('cart_total')}</span><span>SAR ${totalPrice}</span></div>
      <button class="btn-primary" style="width:100%">${t('cart_checkout')}</button>`;
  }
}

