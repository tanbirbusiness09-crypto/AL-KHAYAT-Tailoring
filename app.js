let selectedFabricId = null;

function renderFabricPanel(filter = 'all') {
  const container = document.getElementById('fabric-panel-list');
  if(!container) return;
  let list = fabricProducts;
  if(filter === 'new')        list = list.filter(f => f.badge === 'New');
  else if(filter === 'bestseller') list = list.filter(f => f.isBestseller);
  else if(filter === 'discount')   list = list.filter(f => f.old_price > 0);
  else if(filter !== 'all')        list = list.filter(f => f.origin === filter);

  container.innerHTML = list.map(f => {
    const name = currentLang === 'en' ? f.name_en : f.name_ar;
    const discount = f.old_price > 0 ? Math.round((1 - f.price / f.old_price) * 100) : 0;
    const isSelected = selectedFabricId === f.id;
    return `
      <div class="fabric-item ${isSelected ? 'selected' : ''}" onclick="selectFabricItem(${f.id})">
        <div class="fi-img-wrap">
          <img src="${f.img}" alt="${name}">
        </div>
        <div class="fi-info">
          <div class="fi-name">${name}</div>
          <div class="fi-meta">
            ${f.badge === 'New' ? '<span class="fi-tag new">🆕 New</span>' : ''}
            ${f.isBestseller ? '<span class="fi-tag hot">🔥 Best Seller</span>' : ''}
            ${discount > 0 ? `<span class="fi-tag disc">-${discount}%</span>` : ``}
          </div>
          <div class="fi-sales">🛒 Sold: <strong>${f.salesCount}</strong> times</div>
        </div>
        <div class="fi-price-wrap">
          <div class="fi-price">SAR ${f.price}</div>
          ${f.old_price ? `<div class="fi-old">SAR ${f.old_price}</div>` : ``}
        </div>
      </div>`;

  }).join('') || `<div class="fi-empty">No results for this filter</div>`;
}

function filterFabricPanel(filter, btn) {
  document.querySelectorAll('.ftag').forEach(b => b.classList.remove('active'));
  if(btn) btn.classList.add('active');
  renderFabricPanel(filter);
}

