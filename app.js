// ============ MODAL IMAGE ZOOM ============
function initModalZoom(container) {
  if (!container) return;
  
  // Remove old listeners by cloning
  const newContainer = container.cloneNode(true);
  container.parentNode.replaceChild(newContainer, container);
  
  let isZoomed = false;
  
  // Desktop: hover to zoom, move to pan
  newContainer.addEventListener('mouseenter', () => {
    isZoomed = true;
    newContainer.classList.add('zoomed');
  });
  
  newContainer.addEventListener('mouseleave', () => {
    isZoomed = false;
    newContainer.classList.remove('zoomed');
  });
  
  newContainer.addEventListener('mousemove', (e) => {
    if (!isZoomed) return;
    const rect = newContainer.getBoundingClientRect();
    const x = ((e.clientX - rect.left) / rect.width) * 100;
    const y = ((e.clientY - rect.top) / rect.height) * 100;
    newContainer.style.setProperty('--zoom-x', x + '%');
    newContainer.style.setProperty('--zoom-y', y + '%');
  });
  
  // Mobile: tap to toggle zoom
  newContainer.addEventListener('touchstart', (e) => {
    e.preventDefault();
    isZoomed = !isZoomed;
    newContainer.classList.toggle('zoomed', isZoomed);
    if (isZoomed) {
      const touch = e.touches[0];
      const rect = newContainer.getBoundingClientRect();
      const x = ((touch.clientX - rect.left) / rect.width) * 100;
      const y = ((touch.clientY - rect.top) / rect.height) * 100;
      newContainer.style.setProperty('--zoom-x', x + '%');
      newContainer.style.setProperty('--zoom-y', y + '%');
    }
  }, { passive: false });
  
  newContainer.addEventListener('touchmove', (e) => {
    if (!isZoomed) return;
    e.preventDefault();
    const touch = e.touches[0];
    const rect = newContainer.getBoundingClientRect();
    const x = ((touch.clientX - rect.left) / rect.width) * 100;
    const y = ((touch.clientY - rect.top) / rect.height) * 100;
      newContainer.style.setProperty('--zoom-x', x + '%');
    newContainer.style.setProperty('--zoom-y', y + '%');
  }, { passive: false });
}

