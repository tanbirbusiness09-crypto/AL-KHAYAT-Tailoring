function selectFabricItem(id) {
  selectedFabricId = id;
  const f = fabricProducts.find(x => x.id === id);
  if(!f) return;
  renderFabricPanel(document.querySelector('.ftag.active')?.dataset?.filter || 'all');
  const name = currentLang === 'en' ? f.name_en : f.name_ar;
  document.getElementById('fsi-name').textContent = name;
  const discount = f.old_price > 0 ? ` (${Math.round((1-f.price/f.old_price)*100)}% off!)` : '';
  document.getElementById('fsi-price').textContent = `SAR ${f.price}${f.old_price ? ` (was SAR ${f.old_price}${discount})` : ''}`;
  document.getElementById('fabric-selected-info').style.display = 'flex';
  const notes = document.getElementById('bk-notes');
  if(notes && !notes.value.includes('Fabric:')) {
    notes.value = (notes.value ? notes.value + '\n' : '') + `Fabric: ${name} (SAR ${f.price})`;
  }
}

