function initFloatingAnimation() {
  const elements = document.querySelectorAll('.floating-element');
  if(elements.length === 0) return;
  
  floatingElementsNodes = Array.from(elements).map(el => ({
    el: el,
    x: 0, 
    y: 0,
    targetX: (Math.random() - 0.5) * 40,
    targetY: (Math.random() - 0.5) * 40,
    startTime: performance.now(),
    duration: 3000 + Math.random() * 2000
  }));

  if(floatingAnimationId) cancelAnimationFrame(floatingAnimationId);
  updateFloatingPositions(performance.now());
}

function updateFloatingPositions(timestamp) {
  floatingElementsNodes.forEach(item => {
    const elapsed = timestamp - item.startTime;
    const progress = Math.min(elapsed / item.duration, 1);

    if (progress === 1) {
      item.x = item.targetX;
      item.y = item.targetY;
      item.targetX = (Math.random() - 0.5) * 40;
      item.targetY = (Math.random() - 0.5) * 40;
      item.startTime = timestamp;
      item.duration = 3000 + Math.random() * 2000;
    } else {
      const currentX = item.x + (item.targetX - item.x) * progress;
      const currentY = item.y + (item.targetY - item.y) * progress;
      item.el.style.transform = `translate3d(${currentX}px, ${currentY}px, 0)`;
    }
  });

  floatingAnimationId = requestAnimationFrame(updateFloatingPositions);
}

