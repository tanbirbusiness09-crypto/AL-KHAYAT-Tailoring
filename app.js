function initSlider() {
  const slides = document.querySelectorAll('.hero-slide');
  const dots = document.querySelectorAll('.slider-dot');
  function goToSlide(n) {
    slides.forEach(s => s.classList.remove('active'));
    dots.forEach(d => d.classList.remove('active'));
    currentSlide = (n + slides.length) % slides.length;
    slides[currentSlide].classList.add('active');
    dots[currentSlide].classList.add('active');
  }
  dots.forEach((d, i) => d.addEventListener('click', () => { goToSlide(i); resetInterval(); }));
  slideInterval = setInterval(() => goToSlide(currentSlide + 1), 5000);
  function resetInterval() { clearInterval(slideInterval); slideInterval = setInterval(() => goToSlide(currentSlide + 1), 5000); }
  window.nextSlide = () => { goToSlide(currentSlide + 1); resetInterval(); };
  window.prevSlide = () => { goToSlide(currentSlide - 1); resetInterval(); };
}

