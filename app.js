function buyNow(id) {
  // Add to cart directly, then navigate to checkout
  const p = products.find(x => x.id === id);
  if (p) {
    const existing = cart.find(c => c.id === id);
    // Use qty from modal if it's open, else 1
    const qtyEl = document.getElementById('modal-qty');
    const addQty = qtyEl ? parseInt(qtyEl.textContent) : 1;

    if (existing) {
      existing.qty += addQty;
    } else {
      cart.push({ ...p, qty: addQty });
    }
    updateCartUI();
  }
  closeModal();
  navigateTo('checkout');
}

function closeModal() {
  const modal = document.getElementById('product-modal');
  modal.classList.remove('active');
  // Reset zoom state
  const modalImg = modal.querySelector('.modal-img');
  if (modalImg) modalImg.classList.remove('zoomed');
}

function changeQty(d) {
  const el = document.getElementById('modal-qty');
  let v = parseInt(el.textContent) + d;
  if (v < 1) v = 1;
  el.textContent = v;
}

// ============ CART ============
function addToCart(id) {
  const p = products.find(x => x.id === id);
  if (!p) return;
  const existing = cart.find(c => c.id === id);
  if (existing) existing.qty++;
  else cart.push({ ...p, qty: 1 });
  updateCartUI();
  openCart();
}

function removeFromCart(id) {
  cart = cart.filter(c => c.id !== id);
  updateCartUI();
}

