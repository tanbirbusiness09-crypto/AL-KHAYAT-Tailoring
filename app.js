function autoDetectLocation() {
  if (!navigator.geolocation) {
    showGeoStatus('error', currentLang === 'en' ? 'Geolocation is not supported by your browser.' : 'المتصفح لا يدعم تحديد الموقع.');
    return;
  }
  const btn = document.getElementById('geo-btn-text');
  const btnEl = btn?.closest('button');
  if(btn) btn.textContent = currentLang === 'en' ? 'Detecting...' : 'جاري التحديد...';
  if(btnEl) btnEl.classList.add('geo-loading');
  showGeoStatus('info', currentLang === 'en' ? '📍 Requesting location permission...' : '📍 جاري طلب إذن الموقع...');

  navigator.geolocation.getCurrentPosition(
    async (pos) => {
      const { latitude, longitude } = pos.coords;
      showGeoStatus('info', currentLang === 'en' ? '🔍 Fetching address...' : '🔍 جاري جلب العنوان...');
      try {
        const res = await fetch(
          `https://nominatim.openstreetmap.org/reverse?format=json&lat=${latitude}&lon=${longitude}&accept-language=${currentLang === 'ar' ? 'ar' : 'en'}`,
          { headers: { 'User-Agent': 'AlKhayatTailoring/1.0' } }
        );
        const data = await res.json();
        if (data && data.display_name) {
          const addr = data.display_name;
          document.getElementById('bk-address').value = addr;
          // Auto-select city
          const cityMap = {
            'Riyadh': 'riyadh', 'الرياض': 'riyadh',
            'Jeddah': 'jeddah', 'جدة': 'jeddah',
            'Dammam': 'dammam', 'الدمام': 'dammam',
            'Mecca': 'mecca', 'مكة': 'mecca',
            'Medina': 'medina', 'المدينة': 'medina',
          };
          const cityEl = document.getElementById('bk-city');
          for (const [key, val] of Object.entries(cityMap)) {
            if (addr.includes(key)) { cityEl.value = val; break; }
          }
          showGeoStatus('success', currentLang === 'en' ? '✅ Location detected successfully!' : '✅ تم تحديد الموقع بنجاح!');
          if(btn) btn.textContent = currentLang === 'en' ? 'Location Detected ✓' : 'تم التحديد ✓';
          if(btnEl) { btnEl.classList.remove('geo-loading'); btnEl.classList.add('geo-done'); }
        } else {
          throw new Error('No address found');
        }
      } catch(e) {
        showGeoStatus('error', currentLang === 'en' ? '⚠️ Could not fetch address. Please enter manually.' : '⚠️ تعذر جلب العنوان. يرجى الإدخال يدوياً.');
        if(btn) btn.textContent = currentLang === 'en' ? 'Use My Location' : 'استخدم موقعي';
        if(btnEl) btnEl.classList.remove('geo-loading');
      }
    },
    (err) => {
      const msgs = {
        1: currentLang === 'en' ? '🚫 Location permission denied. Please enable in browser settings.' : '🚫 تم رفض إذن الموقع. يرجى التمكين في إعدادات المتصفح.',
        2: currentLang === 'en' ? '📡 Location unavailable. Please enter address manually.' : '📡 الموقع غير متاح. يرجى إدخال العنوان يدوياً.',
        3: currentLang === 'en' ? '⏱️ Location request timed out.' : '⏱️ انتهت مهلة طلب الموقع.',
      };
      showGeoStatus('error', msgs[err.code] || (currentLang === 'en' ? 'Location error.' : 'خطأ في الموقع.'));
      if(btn) btn.textContent = currentLang === 'en' ? 'Use My Location' : 'استخدم موقعي';
      if(btnEl) btnEl.classList.remove('geo-loading');
    },
    { timeout: 10000, enableHighAccuracy: true }
  );
}

